#!/usr/bin/env node
"use strict";

// One-shot JSON -> PostgreSQL importer. Dry-run is the default.
// Apply requires an explicit flag, DATABASE_URL, psql, an empty target schema,
// and zero uploaded documents until a real file-byte/object-storage migration exists.
const fs = require("node:fs");
const path = require("node:path");
const { spawnSync } = require("node:child_process");
const { validateSnapshot } = require("./preflight-json-migration.cjs");

const TABLES = ["users", "quizzes", "uploaded_documents", "attempts", "api_keys", "payment_orders", "subscriptions"];

function sql(value) {
  if (value === undefined || value === null) return "NULL";
  if (typeof value === "boolean") return value ? "TRUE" : "FALSE";
  if (typeof value === "number") {
    if (!Number.isFinite(value)) throw new Error("Cannot serialize a non-finite number");
    return String(value);
  }
  return "'" + String(value).replace(/'/g, "''") + "'";
}
function jsonb(value) {
  return sql(JSON.stringify(value)) + "::jsonb";
}
function timestamp(value) {
  return value == null ? "NULL" : sql(value) + "::timestamptz";
}
function insert(table, columns, rows) {
  if (!rows.length) return "";
  const values = rows.map(row => "(" + row.map(value => value).join(", ") + ")").join(",\n");
  return "INSERT INTO " + table + " (" + columns.join(", ") + ") VALUES\n" + values + ";\n";
}
function buildSql(snapshot) {
  const chunks = [
    "-- Generated by scripts/import-json-to-postgres.cjs; review and keep private.",
    "BEGIN;",
    "DO $$ BEGIN",
    "  IF " + TABLES.map(table => "EXISTS (SELECT 1 FROM " + table + " LIMIT 1)").join(" OR ") + " THEN",
    "    RAISE EXCEPTION 'Refusing import: target tables must all be empty';",
    "  END IF;",
    "END $$;"
  ];
  chunks.push(insert("users", ["id", "name", "email", "password_hash"], snapshot.users.map(x => [sql(x.id), sql(x.name), sql(x.email), sql(x.password)])));
  // Document bytes are deliberately not imported here. Apply mode refuses snapshots
  // with documents until a verified storage mapping has been implemented.
  chunks.push(insert("quizzes", ["id", "title", "description", "questions", "owner_user_id", "source_document_id", "created_at"], snapshot.quizzes.map(x => [
    sql(x.id), sql(x.title), sql(x.description), jsonb(x.questions), sql(x.ownerUserId), sql(x.sourceDocumentId), timestamp(x.createdAt)
  ])));
  chunks.push(insert("attempts", ["id", "user_id", "quiz_id", "score", "total_questions", "percentage", "passed", "created_at"], snapshot.attempts.map(x => [
    sql(x.id), sql(x.userId), sql(x.quizId), sql(x.score), sql(x.totalQuestions), sql(x.percentage), sql(x.passed), timestamp(x.createdAt)
  ])));
  chunks.push(insert("api_keys", ["id", "owner_user_id", "name", "key_hash", "prefix", "created_at", "expires_at", "last_used_at", "revoked_at"], snapshot.apiKeys.map(x => [
    sql(x.id), sql(x.ownerUserId), sql(x.name), sql(x.keyHash), sql(x.prefix), timestamp(x.createdAt), timestamp(x.expiresAt), timestamp(x.lastUsedAt), timestamp(x.revokedAt)
  ])));
  chunks.push(insert("payment_orders", ["id", "user_id", "plan_id", "amount_paisa", "pidx", "status", "created_at", "paid_at", "transaction_id"], snapshot.paymentOrders.map(x => [
    sql(x.id), sql(x.userId), sql(x.planId), sql(x.amountPaisa), sql(x.pidx), sql(x.status), timestamp(x.createdAt), timestamp(x.paidAt), sql(x.transactionId)
  ])));
  chunks.push(insert("subscriptions", ["user_id", "plan_id", "starts_at", "expires_at", "payment_order_id"], snapshot.subscriptions.map(x => [
    sql(x.userId), sql(x.planId), timestamp(x.startsAt), timestamp(x.expiresAt), sql(x.paymentOrderId)
  ])));
  chunks.push("COMMIT;\n");
  return chunks.filter(Boolean).join("\n");
}
function readSnapshot(input) {
  return JSON.parse(fs.readFileSync(path.resolve(input), "utf8"));
}
function main(argv = process.argv.slice(2), env = process.env) {
  const apply = argv.includes("--apply");
  const args = argv.filter(arg => arg !== "--apply");
  if (args.length > 1 || args.includes("--help")) {
    console.log("Usage: node scripts/import-json-to-postgres.cjs [snapshot.json] [--apply]");
    console.log("Default is a read-only dry-run. Apply requires DATABASE_URL and psql.");
    return args.includes("--help") ? 0 : 2;
  }
  const input = args[0] || env.DATA_FILE || path.join(process.cwd(), "data", "store.json");
  let snapshot;
  try {
    snapshot = readSnapshot(input);
  } catch (error) {
    console.error("Cannot read/parse snapshot (file missing, invalid JSON, or unreadable).");
    return 1;
  }
  const validation = validateSnapshot(snapshot);
  console.log("IIA JSON -> PostgreSQL import " + (apply ? "APPLY" : "DRY-RUN"));
  console.log("Record counts: " + JSON.stringify(validation.counts));
  for (const warning of validation.warnings) console.log("WARNING: " + warning);
  if (validation.errors.length) {
    for (const error of validation.errors) console.error("ERROR: " + error);
    console.error("Stopped before database access; fix all validation errors.");
    return 1;
  }
  if (apply && snapshot.uploadedDocuments.length > 0) {
    console.error("Apply refused: uploaded documents exist. Migrate and verify file bytes/object storage first; no database connection was opened.");
    return 1;
  }
  if (!apply) {
    console.log("PASS: validation only. No database connection or data changes occurred.");
    console.log("To apply, first back up the source and use an empty, disposable PostgreSQL database with the schema applied.");
    return 0;
  }
  if (!env.DATABASE_URL) {
    console.error("Apply refused: DATABASE_URL is required; its value is never printed.");
    return 2;
  }
  const sqlText = buildSql(snapshot);
  const result = spawnSync("psql", ["-X", "--no-psqlrc", "-v", "ON_ERROR_STOP=1", "--dbname", env.DATABASE_URL], {
    input: sqlText, encoding: "utf8", maxBuffer: 4 * 1024 * 1024
  });
  if (result.error) {
    console.error("Could not run psql. Install PostgreSQL client tools; no import success is claimed.");
    return 1;
  }
  if (result.status !== 0) {
    console.error("Import failed; PostgreSQL transaction should have rolled back. Check database-side error output without sharing secrets.");
    if (result.stderr) console.error(result.stderr.slice(-3000));
    return result.status || 1;
  }
  console.log("Import transaction completed. Verify per-table counts and checksums before any application cutover.");
  return 0;
}
if (require.main === module) process.exitCode = main();
module.exports = { buildSql, sql, main };
